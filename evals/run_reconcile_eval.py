# Lines that are supposed to resolve as a PARTIAL payment (less than
# the invoice's full total), from PARTIAL_SUPPLIER_PAYMENTS and the one
# "partial" entry in SALES_PLAN.
EXPECTED_PARTIAL = {"2026/011", "IG-00501", "CBS-2026-0005"}


def score(decisions: list[match.MatchDecision]) -> dict:
    by_key = {(d.bank_line.txn_date.isoformat(), d.bank_line.description): d for d in decisions}
    assert set(by_key) == set(GROUND_TRUTH), (
        "GROUND_TRUTH doesn't line up with the bank lines actually loaded - "
        "has data/synthetic/bank/statement.csv changed? "
        f"missing: {set(GROUND_TRUTH) - set(by_key)}, extra: {set(by_key) - set(GROUND_TRUTH)}"
    )

    correctly_matched: list[tuple[str, str]] = []
    false_matches: list[dict] = []
    missed_matches: list[dict] = []
    partials_detected: list[str] = []
    partials_missed: list[dict] = []
    unmatched_line_found = False
    ambiguous: list[dict] = []

    for key, expected in GROUND_TRUTH.items():
        decision = by_key[key]
        got = decision.invoice_numbers[0] if decision.invoice_numbers else None

        if decision.category == "ambiguous":
            ambiguous.append({"line": key, "candidates": decision.invoice_numbers, "expected": expected})
            continue

        if expected is None:
            if decision.category == "unmatched":
                unmatched_line_found = True
            else:
                false_matches.append({"line": key, "expected": None, "got": got})
            continue

        if got is None:
            missed_matches.append({"line": key, "expected": expected})
            if expected in EXPECTED_PARTIAL:
                partials_missed.append({"line": key, "expected": expected})
            continue

        if got != expected:
            false_matches.append({"line": key, "expected": expected, "got": got})
            continue

        correctly_matched.append((key[1], got))
        if expected in EXPECTED_PARTIAL:
            if decision.category == "partial":
                partials_detected.append(expected)
            else:
                partials_missed.append({"line": key, "expected": expected, "got_category": decision.category})

    real_matches_expected = sum(1 for expected in GROUND_TRUTH.values() if expected is not None)

    return {
        "total_lines": len(GROUND_TRUTH),
        "real_matches_expected": real_matches_expected,
        "correctly_matched": correctly_matched,
        "false_matches": false_matches,
        "missed_matches": missed_matches,
        "partials_detected": partials_detected,
        "partials_missed": partials_missed,
        "unmatched_line_found": unmatched_line_found,
        "ambiguous": ambiguous,
    }


def build_report(data: dict, decisions: list[match.MatchDecision]) -> tuple[str, dict]:
    category_tally: dict[str, int] = {}
    for d in decisions:
        category_tally[d.category] = category_tally.get(d.category, 0) + 1

    md = []
    md.append(f"# Reconciliation eval - {data['timestamp']}")
    md.append("")
    md.append(f"Scored against {data['total_lines']} bank lines (see module docstring for ground truth).")
    md.append("")
    md.append("## Decision categories")
    md.append("")
    md.append("| Category | Count |")
    md.append("| --- | --- |")
    for cat in sorted(category_tally):
        md.append(f"| {cat} | {category_tally[cat]} |")
    md.append("")
    md.append("## Scoring")
    md.append("")
    md.append(
        f"- Correctly matched (right invoice identified): "
        f"{len(data['correctly_matched'])}/{data['real_matches_expected']}"
    )
    md.append(
        f"- **False matches (wrong invoice - the dangerous error): {len(data['false_matches'])}**"
    )
    md.append(f"- Missed matches (should have matched, matched nothing): {len(data['missed_matches'])}")
    md.append(f"- Partial payments correctly detected: {len(data['partials_detected'])}/{len(EXPECTED_PARTIAL)}")
    md.append(f"- Partial payments missed: {len(data['partials_missed'])}")
    md.append(f"- The one genuinely unmatched line correctly left unmatched: {data['unmatched_line_found']}")
    md.append(f"- Ambiguous lines (never auto-resolved, always need a human): {len(data['ambiguous'])}")
    md.append("")

    if data["false_matches"]:
        md.append("### False matches (review these first)")
        md.append("")
        md.append("| Line | Expected | Got |")
        md.append("| --- | --- | --- |")
        for item in data["false_matches"]:
            md.append(f"| {item['line']} | {item['expected']} | {item['got']} |")
        md.append("")

    if data["missed_matches"]:
        md.append("### Missed matches")
        md.append("")
        for item in data["missed_matches"]:
            md.append(f"- {item['line']} (expected {item['expected']})")
        md.append("")

    if data["ambiguous"]:
        md.append("### Ambiguous lines")
        md.append("")
        for item in data["ambiguous"]:
            md.append(f"- {item['line']}: candidates {item['candidates']} (expected {item['expected']})")
        md.append("")

    markdown_text = "\n".join(md)
    json_data = {
        "timestamp": data["timestamp"],
        "total_lines": data["total_lines"],
        "real_matches_expected": data["real_matches_expected"],
        "decision_categories": category_tally,
        "correctly_matched_count": len(data["correctly_matched"]),
        "false_matches": data["false_matches"],
        "missed_matches": data["missed_matches"],
        "partials_detected": data["partials_detected"],
        "partials_missed": data["partials_missed"],
        "unmatched_line_found": data["unmatched_line_found"],
        "ambiguous": data["ambiguous"],
    }
    return markdown_text, json_data


def write_report(markdown_text: str, json_data: dict, md_path: Path, json_path: Path) -> None:
    md_path.parent.mkdir(parents=True, exist_ok=True)
    md_path.write_text(markdown_text)
    json_path.write_text(json.dumps(json_data, indent=2, default=str))


def main(argv: list[str] | None = None) -> int:
    bank_lines = match.load_bank_statement(config.BANK_STATEMENT_PATH)
    payables = ledger.load_payable_obligations(config.ANSWER_KEY_PATH)
    receivables = ledger.load_receivable_obligations(config.SALES_INVOICES_PATH)
    decisions = match.reconcile(bank_lines, payables + receivables)

    data = score(decisions)
    timestamp = datetime.now().strftime("%Y-%m-%d_%H%M")
    data["timestamp"] = timestamp
    markdown_text, json_data = build_report(data, decisions)

    md_path = RESULTS_DIR / f"{timestamp}_reconcile.md"
    json_path = RESULTS_DIR / f"{timestamp}_reconcile.json"
    write_report(markdown_text, json_data, md_path, json_path)

    print(f"Correctly matched: {len(data['correctly_matched'])}/{data['real_matches_expected']}")
    print(f"False matches: {len(data['false_matches'])}")
    print(f"Missed matches: {len(data['missed_matches'])}")
    print(f"Partials detected: {len(data['partials_detected'])}/{len(EXPECTED_PARTIAL)}")
    print(f"Unmatched line correctly found: {data['unmatched_line_found']}")
    print(f"Ambiguous lines: {len(data['ambiguous'])}")
    print(f"\nReport written to:\n  {md_path}\n  {json_path}")

    return 1 if data["false_matches"] else 0


if __name__ == "__main__":
    sys.exit(main())
