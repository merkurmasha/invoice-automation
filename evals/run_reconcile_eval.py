"""Eval harness for bank reconciliation (src/reconcile/).

Runnable as:
    python -m evals.run_reconcile_eval

No Claude API call anywhere in this module or in src/reconcile/ - the
whole point of this phase is that reconciliation is plain deterministic
code (see CLAUDE.md), so there's no "yes" prompt to confirm here.

--- Ground truth ------------------------------------------------------

data/synthetic/bank/statement.csv was generated by
src/synthetic/sales_bank.py's build_bank_lines(), which knows exactly
which invoice (or nothing at all) each line is supposed to pay:

  - one bank line per unique (supplier, invoice_number) in the
    supplier job list, EXCEPT the invoices listed in
    UNPAID_SUPPLIER_STEMS (never paid - and never a bank line at all)
    and CREDIT_NOTE documents (also never a bank line);
  - PARTIAL_SUPPLIER_PAYMENTS pays only part of an invoice's total;
  - one sales-invoice payment line per invoice with paid_amount > 0 in
    SALES_PLAN (sales_invoices.csv's own build_sales_invoices());
  - exactly one line (the bank fee) that matches nothing in either
    ledger.

GROUND_TRUTH below was built BY READING that generator code and the
committed statement.csv side by side - this file doesn't re-run the
generator (its random reference-text/date choices are already baked
into the committed CSV), it just records, for every one of the 37
lines, which invoice_number it should resolve to (None for the one
genuinely unmatched line) and whether the correct outcome is a partial
payment. If the generator or the statement ever change, this table
needs updating by hand - there's no way to derive it automatically
without re-deriving it from the generator's source by eye, which is
exactly what was done here.
"""

